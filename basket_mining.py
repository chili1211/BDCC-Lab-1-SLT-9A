# turning rules into store actions
# --------------------------------------------------------------------
def pull_through(rules, bap, top=5):
    """
    Profitable items each loss leader pulls into the basket.

    For a rule ``{loss leader} -> j`` the expected pulled profit per
    loss-leader basket is ``confidence * own_margin_j``; the *extra*
    part, compared with an average basket, is
    ``(confidence - relSup(j)) * own_margin_j``.

    Parameters
    ----------
    rules : pandas.DataFrame
        Output of `assoc` (training baskets).
    bap : pandas.DataFrame
        Output of `basket_adjusted_profit`.
    top : int
        Consequents kept per loss leader.

    Returns
    -------
    pandas.DataFrame
        One row per (loss leader, pulled item).
    """
    leaders = bap.index[bap["quadrant"] == "Loss leader"]
    r = rules[(rules["n_ante"] == 1) & (rules["lift"] > 1)].copy()
    r["leader"] = r["antecedent"].str[0]
    r = r[r["leader"].isin(leaders) & r["consequent"].isin(bap.index)]
    r["cons_margin"] = r["consequent"].map(bap["own_margin"])
    r = r[r["cons_margin"] > 0]
    rel_cons = r["confidence"] / r["lift"]  # = relSup(j)
    r["extra_profit"] = (r["confidence"] - rel_cons) * r["cons_margin"]
    r["leader_margin"] = r["leader"].map(bap["own_margin"])
    r = r.sort_values(["leader", "extra_profit"], ascending=[True, False])
    out = r.groupby("leader").head(top)
    return out[["leader", "leader_margin", "consequent", "cons_margin",
                "confidence", "lift", "extra_profit"]].reset_index(drop=True)


def bundle_pairs(rules, bap, min_lift=1.5):
    """
    High-lift pairs worth bundling or shelving together.

    A pair qualifies if its lift is at least `min_lift` and the two
    items together earn a positive own margin. Pairs are ranked by
    ``lift * combined own margin * support`` so that a bundle has to be
    strongly associated, profitable *and* common.

    Returns
    -------
    pandas.DataFrame
        One row per unordered pair.
    """
    r = rules[rules["n_ante"] == 1].copy()
    r["a"] = r["antecedent"].str[0]
    r["b"] = r["consequent"]
    r = r[r["a"] < r["b"]]  # pair appears twice; keep one direction
    r = r[r["a"].isin(bap.index) & r["b"].isin(bap.index)]
    r["margin_a"] = r["a"].map(bap["own_margin"])
    r["margin_b"] = r["b"].map(bap["own_margin"])
    r["pair_margin"] = r["margin_a"] + r["margin_b"]
    r["quad_a"] = r["a"].map(bap["quadrant"])
    r["quad_b"] = r["b"].map(bap["quadrant"])
    r = r[(r["lift"] >= min_lift) & (r["pair_margin"] > 0)]
    r["score"] = r["lift"] * r["pair_margin"] * r["support"]
    return r.sort_values("score", ascending=False)[
        ["a", "b", "quad_a", "quad_b", "support", "lift",
         "margin_a", "margin_b", "pair_margin", "score"]
    ].reset_index(drop=True)


