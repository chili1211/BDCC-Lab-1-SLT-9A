def pair_rules(db, rel_minsup):
    """Pair rules (one item each side) for a set of baskets."""
    n = len(db)
    sup = frequent_itemsets(db, max(2, int(np.ceil(rel_minsup * n))), zmax=2)
    r = assoc(sup, n)
    return r[r["n_ante"] == 1].assign(
        pair=lambda d: [tuple(sorted((a[0], c)))
                        for a, c in zip(d["antecedent"], d["consequent"])]
    )


def segment_rules(item_basket, baskets, groups, rel_minsup, top=20):
    """
    Compare the strongest pair rules across basket segments.

    Parameters
    ----------
    item_basket, baskets : pandas.DataFrame
        Output of `data_prep.make_baskets`.
    groups : dict
        ``{segment name: boolean mask over baskets}``.
    rel_minsup : float
        Relative minimum support inside each segment.
    top : int
        Number of highest-lift pairs kept per segment.

    Returns
    -------
    tuple
        ``(top_pairs, overlap)``: the top pairs per segment, and the
        Jaccard overlap of the top-pair sets between segments.
    """
    tops = {}
    for name, mask in groups.items():
        keep = set(baskets.loc[mask, "basket"])
        db = (item_basket[item_basket["basket"].isin(keep)]
              .groupby("basket")["subclass"].apply(frozenset).tolist())
        r = pair_rules(db, rel_minsup)
        r = r.drop_duplicates("pair").sort_values("lift", ascending=False)
        tops[name] = r.head(top).assign(segment=name, baskets=len(db))
    names = list(tops)
    sets = {k: set(v["pair"]) for k, v in tops.items()}
    overlap = pd.DataFrame(
        [[len(sets[a] & sets[b]) / max(1, len(sets[a] | sets[b]))
          for b in names] for a in names],
        index=names, columns=names,
    )
    return pd.concat(tops.values(), ignore_index=True), overlap
