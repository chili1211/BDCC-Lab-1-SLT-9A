"""
Frequent itemset mining, association rules and basket-adjusted profit.

FP-Growth is run with pyFIM (``fim.fpgrowth``), the library used in
class. If pyFIM is not installed, a pure-Python pattern-growth fallback
with the same output is used, so the notebook still runs top to bottom.
Rules are always generated by `assoc` below (same logic as the class
``assoc`` function), so both back ends give identical rules.
"""
from collections import Counter

import numpy as np
import pandas as pd

try:
    import fim
    HAS_FIM = True
except ImportError:  # pragma: no cover - depends on the machine
    HAS_FIM = False

QUADRANTS = ["Star", "Loss leader", "Passenger", "Dead weight"]


# --------------------------------------------------------------------
# frequent itemsets and rules
# --------------------------------------------------------------------
def _fpgrowth_py(db, min_count, zmax):
    """
    Pattern growth on projected databases (class FP-Growth, sped up).

    Parameters
    ----------
    db : list of frozenset
        Transactions.
    min_count : int
        Absolute minimum support.
    zmax : int
        Largest itemset size to mine.

    Returns
    -------
    dict
        ``{sorted tuple: support}`` for every frequent itemset.
    """
    out = {}

    def mine(trans, prefix):
        # one pass counts every item in the projected database
        counts = Counter(x for t in trans for x in t)
        frequent = sorted(x for x, c in counts.items() if c >= min_count)
        for pos, item in enumerate(frequent):
            itemset = prefix + (item,)
            out[tuple(sorted(itemset))] = counts[item]
            if len(itemset) >= zmax:
                continue
            # only items after `item` so each itemset is built once
            later = set(frequent[pos + 1:])
            projected = [t & later for t in trans if item in t]
            projected = [t for t in projected if t]
            if projected:
                mine(projected, itemset)

    mine([frozenset(t) for t in db], ())
    return out


def frequent_itemsets(db, min_count, zmax=3):
    """
    Mine all frequent itemsets with FP-Growth.

    Parameters
    ----------
    db : list of frozenset
        Transactions (one set of subclasses per basket).
    min_count : int
        Absolute minimum support.
    zmax : int
        Largest itemset size to mine.

    Returns
    -------
    dict
        ``{sorted tuple of items: absolute support}``.
    """
    if HAS_FIM:
        # negative supp = absolute support in pyFIM
        res = fim.fpgrowth([list(t) for t in db], target="s",
                           supp=-int(min_count), zmin=1, zmax=zmax,
                           report="a")
        return {tuple(sorted(items)): int(s) for items, s in res}
    return _fpgrowth_py(db, int(min_count), zmax)


def assoc(supports, n, minconf=0.0):
    """
    Association rules with one consequent from frequent itemsets.

    Parameters
    ----------
    supports : dict
        ``{sorted tuple: support}`` from `frequent_itemsets`.
    n : int
        Number of transactions.
    minconf : float
        Minimum confidence.

    Returns
    -------
    pandas.DataFrame
        Columns ``antecedent, consequent, support, rel_support,
        confidence, lift``, sorted by decreasing lift, confidence and
        support, then consequent and antecedent.
    """
    rows = []
    for itemset, s in supports.items():
        if len(itemset) < 2:
            continue  # need at least one item on each side
        for cons in itemset:
            ante = tuple(x for x in itemset if x != cons)
            # every subset of a frequent itemset is frequent
            conf = s / supports[ante]
            if conf < minconf:
                continue
            lift = conf / (supports[(cons,)] / n)
            rows.append((ante, cons, s, s / n, conf, lift))
    rules = pd.DataFrame(rows, columns=["antecedent", "consequent",
                                        "support", "rel_support",
                                        "confidence", "lift"])
    rules["n_ante"] = rules["antecedent"].map(len)
    return rules.sort_values(
        ["lift", "confidence", "support", "consequent", "antecedent"],
        ascending=[False, False, False, True, True],
    ).reset_index(drop=True)


def maximal(supports, min_size=2):
    """Maximal frequent itemsets (no frequent superset), largest support first."""
    sets = [frozenset(k) for k in supports]
    by_size = {}
    for s in sets:
        by_size.setdefault(len(s), []).append(s)
    out = []
    for k, s in supports.items():
        if len(k) < min_size:
            continue
        fk = frozenset(k)
        # downward closure: only supersets one item bigger need checking
        if not any(fk < big for big in by_size.get(len(k) + 1, [])):
            out.append((k, s))
    return sorted(out, key=lambda x: (-x[1], -len(x[0]), x[0]))


