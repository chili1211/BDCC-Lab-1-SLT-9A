# basket-adjusted profit
# --------------------------------------------------------------------
def basket_adjusted_profit(item_basket, baskets, min_baskets=30,
                           size_cap=25):
    """
    Own margin, basket halo and basket-adjusted profit (BAP) per subclass.

    For subclass :math:`i` appearing in basket :math:`b` of size
    :math:`n_b` (distinct subclasses) and profit :math:`P_b`:

    * own margin :math:`m_i` = mean of :math:`p_{ib}`, the profit from
      :math:`i` itself in :math:`b`;
    * the other items earn :math:`o_{ib} = P_b - p_{ib}`; a randomly
      chosen item from a size-:math:`n` basket leaves, on average,
      :math:`E_n = \\overline{P_b (n_b-1)/n_b}` (mean over baskets of
      that size) for the rest;
    * halo :math:`h_i` = mean of :math:`o_{ib} - E_{n_b}`;
    * BAP :math:`= m_i + h_i`.

    Basket sizes above `size_cap` are pooled into one size bucket.

    Parameters
    ----------
    item_basket, baskets : pandas.DataFrame
        Output of `data_prep.make_baskets` (training period only).
    min_baskets : int
        Subclasses in fewer baskets are not scored.
    size_cap : int
        Largest basket size kept as its own bucket.

    Returns
    -------
    pandas.DataFrame
        Indexed by subclass with ``n_baskets, revenue, own_margin,
        margin_rate, halo, halo_se, halo_t, bap, quadrant``, plus

        * ``avg_size``: mean size of the baskets the subclass is in;
        * ``naive_halo``: mean profit of the other items minus the
          store's mean basket profit (no size adjustment), kept only to
          show why the size baseline is needed;
        * ``breakeven_share``: for loss-makers with a positive halo,
          ``-own_margin / halo``, the share of the halo that must be
          *caused* by the item for keeping it to pay off (below 1 is
          the same as BAP > 0).
    """
    b = baskets.set_index("basket")
    bucket = b["size"].clip(upper=size_cap)
    # expected profit of the other items, by size bucket
    leave_one_out = b["profit"] * (b["size"] - 1) / b["size"]
    expected = leave_one_out.groupby(bucket).mean()

    ib = item_basket.copy()
    ib["basket_profit"] = ib["basket"].map(b["profit"])
    ib["expected_other"] = ib["basket"].map(bucket).map(expected)
    ib["other"] = ib["basket_profit"] - ib["profit"]
    ib["resid"] = ib["other"] - ib["expected_other"]
    ib["size"] = ib["basket"].map(b["size"])
    # naive halo: same idea, but compared with the average basket overall
    ib["naive_resid"] = ib["other"] - b["profit"].mean()

    g = ib.groupby("subclass")
    out = pd.DataFrame({
        "n_baskets": g.size(),
        "revenue": g["revenue"].sum(),
        "profit": g["profit"].sum(),
        "own_margin": g["profit"].mean(),
        "halo": g["resid"].mean(),
        "halo_se": g["resid"].std() / np.sqrt(g.size()),
        "avg_size": g["size"].mean(),
        "naive_halo": g["naive_resid"].mean(),
    })
    out = out[out["n_baskets"] >= min_baskets].copy()
    out["margin_rate"] = out["profit"] / out["revenue"]
    out["halo_t"] = out["halo"] / out["halo_se"]
    out["bap"] = out["own_margin"] + out["halo"]
    loss_with_halo = (out["own_margin"] < 0) & (out["halo"] > 0)
    out["breakeven_share"] = np.where(
        loss_with_halo, -out["own_margin"] / out["halo"].where(loss_with_halo),
        np.nan)

    med = out["halo"].median()
    pos_m, high_h = out["own_margin"] > 0, out["halo"] > med
    out["quadrant"] = np.select(
        [pos_m & high_h, ~pos_m & high_h, pos_m & ~high_h],
        QUADRANTS[:3], default=QUADRANTS[3],
    )
    out.attrs["halo_median"] = float(med)
    out.attrs["expected_other"] = expected.to_dict()  # plain dict keeps pandas ops happy
    return out.sort_values("bap", ascending=False)


def quadrant_summary(bap):
    """Count, revenue share and profit share by quadrant."""
    tot_rev, tot_prof = bap["revenue"].sum(), bap["profit"].sum()
    q = bap.groupby("quadrant").agg(
        subclasses=("bap", "size"),
        revenue=("revenue", "sum"),
        own_profit=("profit", "sum"),
        median_margin=("own_margin", "median"),
        median_halo=("halo", "median"),
    ).reindex(QUADRANTS)
    q["revenue_share"] = q["revenue"] / tot_rev
    q["own_profit_share"] = q["own_profit"] / tot_prof
    return q


def bap_persistence(bap_train, bap_holdout):
    """
    Check whether BAP measured in training holds up out of time.

    Returns the Spearman correlation of own margin, halo and BAP between
    the two periods, and the share of subclasses keeping their quadrant.
    """
    common = bap_train.index.intersection(bap_holdout.index)
    a, h = bap_train.loc[common], bap_holdout.loc[common]
    res = {
        col: a[col].rank().corr(h[col].rank())
        for col in ["own_margin", "halo", "bap"]
    }
    res["same_quadrant"] = (a["quadrant"] == h["quadrant"]).mean()
    res["subclasses"] = len(common)
    return pd.Series(res)


def size_bias_check(bap):
    r"""
    Show why the halo needs a basket-size baseline.

    Compares the naive halo (other items vs the average basket) with the
    size-adjusted halo: how strongly each one tracks the average size of
    the baskets a subclass sits in, and how many loss-making subclasses
    would be labelled loss leaders by each version.

    Parameters
    ----------
    bap : pandas.DataFrame
        Output of `basket_adjusted_profit`.

    Returns
    -------
    tuple
        ``(summary, crosstab)``: Spearman correlations with basket size,
        and a naive-vs-adjusted label table for loss-making subclasses.
    """
    rank = lambda s: s.rank()
    summary = pd.Series({
        "spearman(avg size, naive halo)":
            rank(bap["avg_size"]).corr(rank(bap["naive_halo"])),
        "spearman(avg size, adjusted halo)":
            rank(bap["avg_size"]).corr(rank(bap["halo"])),
    })
    loss = bap[bap["own_margin"] <= 0]
    naive_lab = np.where(loss["naive_halo"] > bap["naive_halo"].median(),
                         "Loss leader", "Dead weight")
    crosstab = pd.crosstab(
        pd.Series(naive_lab, index=loss.index, name="naive label"),
        loss["quadrant"].rename("size-adjusted label"),
    )
    return summary, crosstab


def delisting_scenarios(bap, shares=np.linspace(0, 1, 21)):
    r"""
    Three-month profit impact of two delisting rules, under uncertainty
    about how much of the halo is causal.

    Removing a loss-making subclass saves its own loss for sure. What it
    costs depends on how much of its halo the item actually *causes*:
    if a share :math:`c` of the halo disappears with it, delisting
    :math:`i` changes profit by

    .. math:: \Delta_i(c) = -n_i m_i - c\, n_i \max(h_i, 0)

    (a negative halo is not treated as a gain). Two rules are compared:

    * **margin rule**: delist every subclass with own margin <= 0;
    * **BAP rule**: delist only loss-makers with BAP < 0.

    The rules differ only on loss-makers with BAP >= 0, so the margin
    rule wins only when :math:`c` is below
    :math:`c^* = \sum(-n_i m_i) / \sum n_i h_i` over those items.

    Parameters
    ----------
    bap : pandas.DataFrame
        Output of `basket_adjusted_profit`.
    shares : array-like
        Causal shares :math:`c` to evaluate.

    Returns
    -------
    tuple
        ``(curves, crossover)``: net impact per rule and share, and
        :math:`c^*` (``None`` if the BAP rule keeps no loss-maker).
    """
    loss = bap[bap["own_margin"] <= 0]
    saved = -loss["profit"]                                   # own loss avoided
    at_risk = loss["n_baskets"] * loss["halo"].clip(lower=0)  # halo if fully causal
    rules = {"Margin rule: cut every loss-maker": loss.index,
             "BAP rule: cut only loss-makers with BAP < 0":
                 loss.index[loss["bap"] < 0]}
    rows = []
    for name, idx in rules.items():
        for c in shares:
            rows.append({"rule": name, "causal_share": c,
                         "net_profit": (saved[idx] - c * at_risk[idx]).sum(),
                         "subclasses": len(idx)})
    kept = loss.index[loss["bap"] >= 0]
    crossover = (saved[kept].sum() / at_risk[kept].sum()
                 if len(kept) and at_risk[kept].sum() > 0 else None)
    curves = pd.DataFrame(rows)
    curves.attrs["kept_saved"] = float(saved[kept].sum())
    curves.attrs["kept_at_risk"] = float(at_risk[kept].sum())
    curves.attrs["kept_n"] = int(len(kept))
    return curves, crossover


